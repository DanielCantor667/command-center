export const PORTFOLIO_TECHNOLOGIES: PortfolioTechnology[] = cvEntries.map((entry) => {
  const names = [entry.name, entry.id, ...entry.aliases].map(normalizeTechnology);
  const recorded = PROJECTS.filter(
    (project) =>
      project.public &&
      project.technologies.some((tech) => names.includes(normalizeTechnology(tech.name))),
  ).map((project) => project.id);
  const projectIds = [...new Set([...entry.projectIds, ...recorded])];
  return { ...entry, projectIds, source: projectIds.length ? 'cv-and-project' : 'cv' };
});

export function filterTechnologies(
  query: string,
  category: TechnologyCategory | 'all' = 'all',
): PortfolioTechnology[] {
  const normalized = normalizeTechnology(query);
  return PORTFOLIO_TECHNOLOGIES.filter(
    (entry) =>
      (category === 'all' || entry.category === category) &&
      [entry.name, entry.id, ...entry.aliases].some((value) =>
        normalizeTechnology(value).includes(normalized),
      ),
  );
}
