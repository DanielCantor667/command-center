"""Phase R.5 (specs/workshop-realism.md): the walkable floor of the lab for the free-walk mode.

  /Applications/Blender.app/Contents/MacOS/Blender --background blender/scenes/workshop-room-proto-v2.blend \
    --python-exit-code 1 --python blender/export_collision.py

Casts a ray down from just above head height over every grid cell: anything hit above the ankles blocks the cell, which
leaves hanging lamps and floor cables out. Writes apps/web/modules/workshop-game/lab-collision.ts, '#' = blocked.
"""
from pathlib import Path

import bpy
from mathutils import Vector

ROOT = Path(__file__).resolve().parents[1]
CELL = 0.1
X0, X1, Y0, Y1 = -4.0, 4.0, -6.1, 4.9  # room interior, as in bake_workshop_lab.py
HEAD, ANKLES = 1.9, 0.12


def movers():
    for o in bpy.data.objects:
        root = o
        while root.parent:
            root = root.parent
        if root.get("role") == "dynamic":
            o.hide_viewport = True


def main():
    movers()
    scene = bpy.context.scene
    bpy.context.view_layer.update()
    graph = bpy.context.evaluated_depsgraph_get()
    down = Vector((0, 0, -1))
    rows = []
    for j in range(round((Y1 - Y0) / CELL)):
        row = ""
        for i in range(round((X1 - X0) / CELL)):
            origin = Vector((X0 + (i + 0.5) * CELL, Y0 + (j + 0.5) * CELL, HEAD))
            hit, *_ = scene.ray_cast(graph, origin, down, distance=HEAD - ANKLES)
            row += "#" if hit else "."
        rows.append(row)
    body = ",\n".join(f"  '{row}'" for row in rows)
    (ROOT / "apps/web/modules/workshop-game/lab-collision.ts").write_text(
        "// Generated by blender/export_collision.py; do not edit by hand.\n"
        f"export const COLLISION = {{ cell: {CELL}, x0: {X0}, zFront: {-Y0}, rows: [\n{body},\n] }};\n")
    print("COLLISION", len(rows), "rows,", sum(r.count("#") for r in rows), "blocked of", sum(len(r) for r in rows))


main()
